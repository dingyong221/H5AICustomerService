export function searchHelp(query: string): readonly HelpTopic[] {
  const words = query.trim().toLocaleLowerCase().split(/\s+/u).filter(Boolean);
  return helpTopics.filter((topic) => {
    const text = [topic.title, topic.summary, ...topic.steps, ...topic.tips, topic.example ?? '']
      .join(' ')
      .toLocaleLowerCase();
    return words.every((word) => text.includes(word));
  });
}

export function manualMarkdown(): string {
  return (
    `# 商家 AI 客服使用手册\n\n更新：${manualUpdated}\n\n本手册覆盖商家后台当前开放的功能。从真实资料开始，核对并发布后再把消费者链接分享给客户。AI 生成文案不等于确认事实，也不会自动保存或发布。\n\n` +
    helpTopics
      .map(
        (topic) =>
          `## ${topic.title}\n\n${topic.summary}\n\n${topic.steps.map((step, index) => `${index + 1}. ${step}`).join('\n')}\n\n${topic.example ? `填写示例：${topic.example}\n\n` : ''}注意事项：\n\n${topic.tips.map((tip) => `- ${tip}`).join('\n')}`,
      )
      .join('\n\n')
  );
}

export function manualText(): string {
  return manualMarkdown()
    .replace(/^#{1,2} /gmu, '')
    .replace(/^- /gmu, '• ');
}
