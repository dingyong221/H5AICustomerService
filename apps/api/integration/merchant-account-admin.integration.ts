import { createHmac, randomBytes, scryptSync } from 'node:crypto';
import type { Connection, RowDataPacket } from 'mysql2/promise';
import { describe, expect, it } from 'vitest';
import {
  AccountResetConflict,
  loadDatabaseConfig,
  MySqlMerchantAccessRepository,
  MySqlMerchantAccountAdminRepository,
} from '@h5cs/database';

// Deliberately fail before opening a connection unless this is the disposable,
// loopback-only CI database. Never inherit a production MYSQL_DATABASE_URL.
const url = process.env['H5CS_INTEGRATION_MYSQL_URL'];
if (!url) throw new Error('Dedicated integration database required');
const target = new URL(url);
if (
  target.protocol !== 'mysql:' ||
  !['localhost', '127.0.0.1'].includes(target.hostname) ||
  target.pathname !== '/h5cs_integration_ci' ||
  target.username !== 'h5cs_ci' ||
  target.search ||
  target.hash
)
  throw new Error('Account fixtures must never run against merchant databases');
const loaded = loadDatabaseConfig({ MYSQL_DATABASE_URL: url, NODE_ENV: 'test', APP_ENV: 'test' });
if (!loaded.configured) throw new Error('Dedicated database unavailable');
const database = loaded.config;
const oldPassword = 'SYNTHETIC-account-old-password-01';
const nextPassword = 'SYNTHETIC-account-new-password-02';
const anotherPassword = 'SYNTHETIC-account-other-password-03';
const phone = '13800138007';
const hex = (value: Buffer) => value.toString('hex');
type Fixture = {
  merchants: readonly [Buffer, Buffer, Buffer];
  users: readonly [Buffer, Buffer];
  key: string;
  admin: MySqlMerchantAccountAdminRepository;
  access: MySqlMerchantAccessRepository;
};

async function fixture(run: (value: Fixture) => Promise<void>) {
  const merchants = [randomBytes(16), randomBytes(16), randomBytes(16)] as const;
  const users = [randomBytes(16), randomBytes(16)] as const;
  const key = randomBytes(32).toString('base64url');
  const connection = await database.openConnection();
  try {
    for (const [index, merchant] of merchants.entries())
      await connection.execute(
        `INSERT INTO merchant (id, name, status, timezone, created_at, updated_at)
       VALUES (?, ?, 'active', 'Asia/Shanghai', UTC_TIMESTAMP(6), UTC_TIMESTAMP(6))`,
        [merchant, `ACCOUNT_ISOLATED_${hex(merchant)}_${index}`],
      );
    for (const [index, user] of users.entries()) {
      await connection.execute(
        `INSERT INTO merchant_user (id, status, created_at, updated_at)
        VALUES (?, 'active', UTC_TIMESTAMP(6), UTC_TIMESTAMP(6))`,
        [user],
      );
      const salt = randomBytes(16);
      const normalizedPhone = `+86${index === 0 ? phone : '13900139007'}`;
      await connection.execute(
        `INSERT INTO merchant_password_credential
        (merchant_user_id, phone_lookup_digest, password_salt, password_hash, created_at, updated_at)
        VALUES (?, ?, ?, ?, UTC_TIMESTAMP(6), UTC_TIMESTAMP(6))`,
        [
          user,
          createHmac('sha256', Buffer.from(key, 'base64url')).update(normalizedPhone).digest(),
          salt,
          scryptSync(oldPassword, salt, 64),
        ],
      );
      for (const merchant of index === 0 ? merchants.slice(0, 2) : merchants.slice(2))
        await connection.execute(
          `INSERT INTO merchant_membership
          (merchant_id, merchant_user_id, role, status, created_at, updated_at)
          VALUES (?, ?, 'owner', 'active', UTC_TIMESTAMP(6), UTC_TIMESTAMP(6))`,
          [merchant, user],
        );
    }
  } finally {
    await connection.end();
  }
  try {
    await run({
      merchants,
      users,
      key,
      admin: new MySqlMerchantAccountAdminRepository(database),
      access: new MySqlMerchantAccessRepository(database, key),
    });
  } finally {
    const cleanup = await database.openConnection();
    try {
      // Only IDs generated by this individual test are removed. No global reset.
      for (const user of users) {
        await cleanup.execute(
          `DELETE FROM audit_log WHERE action = 'merchant.password_reset' AND target_type = 'merchant_user' AND target_id = ?`,
          [hex(user)],
        );
        await cleanup.execute('DELETE FROM platform_login_session WHERE merchant_user_id = ?', [
          user,
        ]);
        await cleanup.execute('DELETE FROM merchant_membership WHERE merchant_user_id = ?', [user]);
        await cleanup.execute(
          'DELETE FROM merchant_password_credential WHERE merchant_user_id = ?',
          [user],
        );
        await cleanup.execute('DELETE FROM merchant_user WHERE id = ?', [user]);
      }
      for (const merchant of merchants)
        await cleanup.execute('DELETE FROM merchant WHERE id = ?', [merchant]);
    } finally {
      await cleanup.end();
    }
  }
}

async function resetInput(f: Fixture) {
  const account = (await f.admin.list(hex(f.merchants[0])))[0]!;
  return {
    merchantId: hex(f.merchants[0]),
    userId: hex(f.users[0]),
    expectedVersion: account.version,
    affectedMerchantIds: account.relatedMerchants.map((merchant) => merchant.id),
    password: nextPassword,
    reason: '忘记密码',
    operatorId: 'synthetic-ci-operator',
  };
}

async function auditFor(user: Buffer) {
  const connection = await database.openConnection();
  try {
    const [rows] = await connection.execute<
      (RowDataPacket & { merchant_id: Buffer; metadata: unknown })[]
    >(
      `SELECT merchant_id, metadata FROM audit_log WHERE action = 'merchant.password_reset' AND target_type = 'merchant_user' AND target_id = ? ORDER BY merchant_id`,
      [hex(user)],
    );
    return rows;
  } finally {
    await connection.end();
  }
}

function barrier() {
  let release!: () => void;
  const promise = new Promise<void>((resolve) => {
    release = resolve;
  });
  return { promise, release };
}

function gatedDatabase(
  afterCredentialLock?: ReturnType<typeof barrier>,
  resume?: ReturnType<typeof barrier>,
  beforeCredentialQuery?: ReturnType<typeof barrier>,
) {
  return {
    ...database,
    openConnection: async () => {
      const connection = await database.openConnection();
      return new Proxy(connection, {
        get(target, property) {
          if (property === 'execute')
            return async (sql: string, values?: Parameters<Connection['execute']>[1]) => {
              const pending = target.execute(sql, values);
              const credentialQuery = sql.includes('FROM merchant_password_credential');
              if (credentialQuery) beforeCredentialQuery?.release();
              const result = await pending;
              if (credentialQuery && sql.includes('FOR UPDATE') && afterCredentialLock && resume) {
                afterCredentialLock.release();
                await resume.promise;
              }
              return result;
            };
          const value: unknown = Reflect.get(target, property);
          return typeof value === 'function' ? value.bind(target) : value;
        },
      }) as Connection;
    },
  };
}

describe('real MySQL operator merchant password administration', () => {
  it('displays fixed login accounts, resets shared accounts, revokes every old session, and preserves unrelated accounts', async () => {
    await fixture(async (f) => {
      const a = hex(f.merchants[0]),
        b = hex(f.merchants[1]),
        c = hex(f.merchants[2]);
      const first = await f.access.login({ phone, password: oldPassword, merchantId: a });
      const second = await f.access.login({
        phone: `m_${hex(f.users[0])}`,
        password: oldPassword,
        merchantId: b,
      });
      const unrelated = await f.access.login({
        phone: `m_${hex(f.users[1])}`,
        password: oldPassword,
        merchantId: c,
      });
      const connection = await database.openConnection();
      try {
        await connection.execute(`UPDATE merchant SET status = 'suspended' WHERE id = ?`, [
          f.merchants[1],
        ]);
      } finally {
        await connection.end();
      }
      const input = await resetInput(f);
      expect(input.affectedMerchantIds.sort()).toEqual([a, b].sort());
      await f.admin.reset(input);
      expect(await f.access.resolveSession(first.sessionToken, a)).toBeNull();
      expect(await f.access.resolveSession(second.sessionToken, b)).toBeNull();
      expect(await f.access.resolveSession(unrelated.sessionToken, c)).not.toBeNull();
      await expect(f.access.login({ phone, password: oldPassword, merchantId: a })).rejects.toThrow(
        '账号、手机号或密码不正确',
      );
      await expect(
        f.access.login({ phone: `m_${hex(f.users[0])}`, password: oldPassword, merchantId: a }),
      ).rejects.toThrow('账号、手机号或密码不正确');
      expect(
        (await f.access.login({ phone, password: nextPassword, merchantId: a })).merchantId,
      ).toBe(a);
      expect(
        (
          await f.access.login({
            phone: `m_${hex(f.users[0])}`,
            password: nextPassword,
            merchantId: a,
          })
        ).merchantId,
      ).toBe(a);
      await expect(
        f.access.login({ phone, password: nextPassword, merchantId: b }),
      ).rejects.toThrow('请选择有权管理的商家');
      const audit = await auditFor(f.users[0]);
      expect(audit.map((row) => hex(row.merchant_id)).sort()).toEqual([a, b].sort());
      for (const row of audit) {
        const metadata: unknown =
          typeof row.metadata === 'string' ? JSON.parse(row.metadata) : row.metadata;
        expect(metadata).toEqual({
          reason: '忘记密码',
          affectedMerchantIds: [a, b].sort(),
          sessionsRevoked: true,
        });
        expect(JSON.stringify(metadata)).not.toContain(nextPassword);
        expect(JSON.stringify(metadata)).not.toContain(oldPassword);
      }
      const refreshed = (await f.admin.list(a))[0]!;
      expect(refreshed.account).toBe(`m_${hex(f.users[0])}`);
      expect(refreshed.version).not.toBe(input.expectedVersion);
      expect(JSON.stringify(refreshed)).not.toMatch(
        /phone_lookup_digest|password_hash|password_salt/u,
      );
    });
  });

  it('rejects a forged merchant scope, changed shared-account membership, stale credential version, and arbitrary audit text', async () => {
    await fixture(async (f) => {
      const input = await resetInput(f),
        a = hex(f.merchants[0]);
      await expect(f.admin.reset({ ...input, userId: hex(f.users[1]) })).rejects.toBeInstanceOf(
        AccountResetConflict,
      );
      await expect(f.admin.reset({ ...input, affectedMerchantIds: [a] })).rejects.toBeInstanceOf(
        AccountResetConflict,
      );
      await expect(f.admin.reset({ ...input, reason: nextPassword })).rejects.toThrow(
        'Invalid reset',
      );
      expect(await auditFor(f.users[0])).toHaveLength(0);
      const oldSession = await f.access.login({ phone, password: oldPassword, merchantId: a });
      expect(await f.access.resolveSession(oldSession.sessionToken, a)).not.toBeNull();
      await f.admin.reset(input);
      await expect(f.admin.reset({ ...input, password: anotherPassword })).rejects.toBeInstanceOf(
        AccountResetConflict,
      );
      expect(await auditFor(f.users[0])).toHaveLength(2);
      expect(
        (await f.access.login({ phone, password: nextPassword, merchantId: a })).merchantId,
      ).toBe(a);
    });
  });

  it('allows only one of two simultaneous resets against the same credential version to commit', async () => {
    await fixture(async (f) => {
      const input = await resetInput(f);
      const result = await Promise.allSettled([
        f.admin.reset(input),
        f.admin.reset({ ...input, password: anotherPassword }),
      ]);
      expect(result.filter((item) => item.status === 'fulfilled')).toHaveLength(1);
      const rejected = result.find((item) => item.status === 'rejected');
      expect(
        rejected?.status === 'rejected' && rejected.reason instanceof AccountResetConflict,
      ).toBe(true);
      const winner = result[0]?.status === 'fulfilled' ? nextPassword : anotherPassword;
      const loser = winner === nextPassword ? anotherPassword : nextPassword;
      expect(
        (await f.access.login({ phone, password: winner, merchantId: input.merchantId }))
          .merchantId,
      ).toBe(input.merchantId);
      await expect(
        f.access.login({ phone, password: loser, merchantId: input.merchantId }),
      ).rejects.toThrow();
      expect(await auditFor(f.users[0])).toHaveLength(2);
    });
  });

  it('revokes a valid old-password login that held the credential lock before the reset', async () => {
    await fixture(async (f) => {
      const input = await resetInput(f),
        locked = barrier(),
        resume = barrier(),
        attempted = barrier();
      const access = new MySqlMerchantAccessRepository(gatedDatabase(locked, resume), f.key);
      const login = access.login({ phone, password: oldPassword, merchantId: input.merchantId });
      try {
        await locked.promise;
        const reset = new MySqlMerchantAccountAdminRepository(
          gatedDatabase(undefined, undefined, attempted),
        ).reset(input);
        await attempted.promise;
        resume.release();
        const session = await login;
        await reset;
        expect(await f.access.resolveSession(session.sessionToken, input.merchantId)).toBeNull();
        await expect(
          f.access.login({ phone, password: oldPassword, merchantId: input.merchantId }),
        ).rejects.toThrow();
      } finally {
        resume.release();
      }
    });
  });

  it('does not issue an old-password session when the reset held the credential lock first', async () => {
    await fixture(async (f) => {
      const input = await resetInput(f),
        locked = barrier(),
        resume = barrier(),
        attempted = barrier();
      const admin = new MySqlMerchantAccountAdminRepository(gatedDatabase(locked, resume));
      const reset = admin.reset(input);
      try {
        await locked.promise;
        const access = new MySqlMerchantAccessRepository(
          gatedDatabase(undefined, undefined, attempted),
          f.key,
        );
        const outcome = Promise.allSettled([
          access.login({ phone, password: oldPassword, merchantId: input.merchantId }),
        ]);
        await attempted.promise;
        resume.release();
        await reset;
        expect((await outcome)[0]?.status).toBe('rejected');
        const connection = await database.openConnection();
        try {
          const [sessions] = await connection.execute<(RowDataPacket & { total: number })[]>(
            `SELECT COUNT(*) total FROM platform_login_session WHERE merchant_user_id = ? AND revoked_at IS NULL`,
            [f.users[0]],
          );
          expect(Number(sessions[0]?.total)).toBe(0);
        } finally {
          await connection.end();
        }
      } finally {
        resume.release();
      }
    });
  });
});
